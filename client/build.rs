use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-env-changed=CARGO_MANIFEST_DIR");
    println!("cargo:rerun-if-changed=../portal/dist");
    println!("cargo:rerun-if-changed=src/webui/index.html");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    let dist_dir = manifest_dir.join("..").join("portal").join("dist");
    let dist_index = dist_dir.join("index.html");
    let fallback_index = manifest_dir.join("src").join("webui").join("index.html");

    let mut assets: Vec<(String, PathBuf)> = Vec::new();
    let from_portal_dist = dist_index.is_file();

    if from_portal_dist {
        collect_files_recursive(&dist_dir, &dist_dir, &mut assets);
        assets.sort_by(|a, b| a.0.cmp(&b.0));
    } else if fallback_index.is_file() {
        let abs = fs::canonicalize(&fallback_index).unwrap_or(fallback_index);
        assets.push(("index.html".to_string(), abs));
    } else {
        panic!(
            "Neither {} nor {} exists for embedding portal assets",
            dist_index.display(),
            fallback_index.display()
        );
    }

    let mut generated = String::with_capacity(4096 + assets.len() * 200);
    generated.push_str("// @generated by client/build.rs — do not edit manually.\n");
    let _ = writeln!(
        generated,
        "#[allow(dead_code)]\npub const PORTAL_FROM_DIST_BUNDLE: bool = {};",
        from_portal_dist
    );
    generated.push_str(
        r#"#[derive(Clone, Copy)]
#[allow(dead_code)]
pub struct PortalAsset {
    pub mime: &'static str,
    pub raw: &'static [u8],
    pub gzip: Option<&'static [u8]>,
    pub etag: &'static str,
    pub immutable: bool,
}

#[allow(dead_code)]
pub fn get_portal_asset_entry(path: &str) -> Option<PortalAsset> {
    let trimmed = path.trim_start_matches('/');
    let key = if trimmed.is_empty() { "index.html" } else { trimmed };
    match key {
"#,
    );

    for (rel_path, abs_path) in &assets {
        let mime = mime_for_path(rel_path);
        let abs_str = abs_path.to_string_lossy();
        let etag = compute_etag(abs_path);
        let mut gz_os = abs_path.as_os_str().to_os_string();
        gz_os.push(".gz");
        let gz_path = PathBuf::from(gz_os);
        let gzip_expr = if gz_path.is_file() {
            format!("Some(include_bytes!({:?}))", gz_path.to_string_lossy())
        } else {
            "None".to_string()
        };
        let immutable = rel_path.starts_with("assets/");
        let _ = writeln!(
            generated,
            "        {:?} => Some(PortalAsset {{ mime: {:?}, raw: include_bytes!({:?}), gzip: {}, etag: {:?}, immutable: {} }}),",
            rel_path, mime, abs_str, gzip_expr, etag, immutable
        );
    }

    generated.push_str("        _ => None,\n");
    generated.push_str("    }\n");
    generated.push_str("}\n\n");
    generated.push_str(
        "#[allow(dead_code)]\npub fn get_portal_asset(path: &str) -> Option<(&'static str, &'static [u8])> {\n    get_portal_asset_entry(path).map(|entry| (entry.mime, entry.raw))\n}\n",
    );

    let dest = out_dir.join("portal_assets.rs");
    fs::write(&dest, generated).expect("write $OUT_DIR/portal_assets.rs");
}

fn collect_files_recursive(root: &Path, current: &Path, out: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", current.display());
    let entries = match fs::read_dir(current) {
        Ok(rd) => rd,
        Err(_) => return,
    };

    let mut sorted_paths: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|de| de.path())).collect();
    sorted_paths.sort();

    for path in sorted_paths {
        let meta = match fs::metadata(&path) {
            Ok(m) => m,
            Err(_) => continue,
        };
        if meta.is_dir() {
            collect_files_recursive(root, &path, out);
        } else if meta.is_file() {
            println!("cargo:rerun-if-changed={}", path.display());
            if let Ok(rel) = path.strip_prefix(root) {
                let rel_norm = rel
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy())
                    .collect::<Vec<_>>()
                    .join("/");
                if !rel_norm.is_empty() && !rel_norm.ends_with(".gz") {
                    let abs = fs::canonicalize(&path).unwrap_or(path);
                    out.push((rel_norm, abs));
                }
            }
        }
    }
}

fn compute_etag(path: &Path) -> String {
    let bytes = fs::read(path).expect("read asset bytes for etag");
    let mut hash: u64 = 0xcbf29ce484222325;
    for &b in &bytes {
        hash ^= u64::from(b);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    format!("\"{:016x}-{}\"", hash, bytes.len())
}

fn mime_for_path(rel_path: &str) -> &'static str {
    let ext = Path::new(rel_path)
        .extension()
        .and_then(|e| e.to_str())
        .map(|e| e.to_ascii_lowercase())
        .unwrap_or_default();

    match ext.as_str() {
        "html" | "htm" => "text/html; charset=utf-8",
        "js" | "mjs" => "application/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "webp" => "image/webp",
        "jpg" | "jpeg" => "image/jpeg",
        "txt" => "text/plain; charset=utf-8",
        "wasm" => "application/wasm",
        _ => "application/octet-stream",
    }
}
